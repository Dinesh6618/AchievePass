#!/usr/bin/env node
/**
 * Concatenates supabase/migrations/*.sql (in order) into ONE file, supabase/setup.sql, so a project can be set up
 * by pasting a single script into the Supabase SQL editor — no CLI or database password needed.
 *
 *   npm run build-sql
 *
 * Run it once on an EMPTY project. (Re-running the whole bundle on a project that already has the schema fails at the
 * first `create type`; use `supabase db push` for later changes.)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = 'supabase/migrations'
const files = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort()

const parts = files.map((f) => `-- ============================================================================\n-- ${f}\n-- ============================================================================\n\n${readFileSync(join(dir, f), 'utf8').trim()}\n`)

const header = `-- CertiPass — complete database setup (GENERATED by \`npm run build-sql\` — edit supabase/migrations instead).
-- Paste this whole file into: Supabase dashboard → SQL Editor → New query → Run.
-- Contents: ${files.join(', ')}
-- For a brand-new project only.

`

writeFileSync('supabase/setup.sql', header + parts.join('\n\n'), 'utf8')
console.log(`supabase/setup.sql written (${files.length} migrations).`)
